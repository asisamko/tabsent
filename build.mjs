// Builds the bookmarklet (focus-bypass.bookmarklet.txt), the install page (index.html) and the
// Chrome extension's guard (extension/guard.js + its manifest version) from focus-bypass.user.js.
// Run after every change to the script: node build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(dir, 'focus-bypass.user.js'), 'utf8');
const code = src.slice(src.indexOf('(() => {')).trim();
const body = code
  .split('\n')
  .map((l) => l.replace(/^\s*\/\/.*$/, '').replace(/\/\*[^*]*\*\//g, '').trim())
  .filter(Boolean)
  .join(' ');
const bookmarklet = `javascript:${encodeURIComponent(body)}void 0`;
fs.writeFileSync(path.join(dir, 'focus-bypass.bookmarklet.txt'), `${bookmarklet}\n`);

// Chrome extension: the same IIFE, plus the userscript's @version in the manifest.
fs.writeFileSync(
  path.join(dir, 'extension', 'guard.js'),
  `// Generated by build.mjs from focus-bypass.user.js – edit that file, then run: node build.mjs\n${code}\n`,
);
const version = src.match(/@version\s+(\S+)/)?.[1];
const manifestPath = path.join(dir, 'extension', 'manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
if (version && manifest.version !== version) {
  manifest.version = version;
  fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
}

